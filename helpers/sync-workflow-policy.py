#!/usr/bin/env python3
"""Generate offline policy engines from the verified engineering release.

Consumers own JSON catalogues and workflow YAML. Engine changes belong to
workflow-library; sync.py --export-sdk generates the flat released files.
Generated copies preserve cold-checkout validation without a network bootstrap.
"""
import argparse
import hashlib
import json
from pathlib import Path
import os
import tempfile

SOURCE = Path(__file__).resolve().parent
FILES = ('workflow_contract.py', 'workflow_operation.py', 'pins_compat.mjs')


def synchronize(root, check=False):
    root = Path(root).resolve(strict=True)
    target = root / '.github'
    if not target.is_dir() or target.is_symlink():
        raise ValueError('caller must supply its existing unlinked .github directory')
    expected = {name: (SOURCE / name).read_bytes() for name in FILES}
    manifest = {'version': 1, 'owner': 'nicodes/tools',
                'sha256': {name: hashlib.sha256(body).hexdigest()
                           for name, body in expected.items()}}
    generated = {target / name: body for name, body in expected.items()}
    bootstrap = root / 'scripts' / 'engineering-bootstrap.py'
    if bootstrap.exists() or bootstrap.is_symlink():
        if bootstrap.parent.is_symlink() or not bootstrap.parent.is_dir():
            raise ValueError('bootstrap parent must be an existing unlinked directory')
        body = (SOURCE / 'engineering-bootstrap.py').read_bytes()
        generated[bootstrap] = body
        manifest['bootstrap_sha256'] = hashlib.sha256(body).hexdigest()
    generated[target / 'workflow-policy.generated.json'] = (
        json.dumps(manifest, sort_keys=True, indent=2) + '\n').encode()
    contract_path = target / 'workflow-contract.json'
    if contract_path.is_symlink() or not contract_path.is_file():
        raise ValueError('caller must supply its unlinked workflow contract')
    contract = json.loads(contract_path.read_text())
    if not isinstance(contract, dict):
        raise ValueError('workflow contract must be an object')
    if check and contract.get('engine_sha256') != manifest['sha256']:
        raise ValueError('workflow contract uses an unreviewed engine generation')
    contract['engine_sha256'] = manifest['sha256']
    if not check:
        generated[contract_path] = (json.dumps(contract, indent=2)+'\n').encode()
    # Refuse all linked destinations before writing any generated byte.
    for path in generated:
        if path.is_symlink() or path.exists() and not path.is_file():
            raise ValueError('generated policy destination is linked or not a file')
    if check:
        if any(not path.is_file() or path.read_bytes() != body
               for path, body in generated.items()):
            raise ValueError('generated workflow policy differs from the verified release')
        return manifest
    for path, body in generated.items():
        descriptor, stage = tempfile.mkstemp(prefix='.policy-', dir=path.parent)
        try:
            with os.fdopen(descriptor, 'wb') as stream:
                stream.write(body)
                stream.flush()
                os.fsync(stream.fileno())
            os.chmod(stage, 0o644)
            os.replace(stage, path)
        finally:
            Path(stage).unlink(missing_ok=True)
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path.cwd())
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    synchronize(args.root, args.check)


if __name__ == '__main__':
    main()
